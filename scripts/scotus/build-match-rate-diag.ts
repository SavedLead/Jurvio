import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { readScdbCsv } from "../../src/modules/scotus/application/import-scdb";
import { scdbDate, scdbInt, scdbText } from "../../src/modules/scotus/domain/scdb";
import { scdbMatchCtes } from "../../src/modules/scotus/application/scdb-matching";

// Writes scripts/diag/scdb-jurvio-match-rate.sql: a read-only report that runs
// the importer's exact SCDB -> legal_case matching rule (scdb-matching.ts)
// against production, with the SCDB docket keys inlined as VALUES (no tables are
// created). Run it with the "Diagnose with a read-only SQL file" workflow.
//   pnpm tsx scripts/scotus/build-match-rate-diag.ts

const root = path.resolve(import.meta.dirname, "../..");
const file = async (p: string) => ({ path: p, bytes: await readFile(path.join(root, p)) });
const lit = (v: string | number | null) => (v === null ? "NULL" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`);

const modern = readScdbCsv(await file("data/scdb/2026_01/SCDB_2026_01_caseCentered_Docket.csv.zip")).rows;
// Same legacy source as the importer: the first row of each case in the
// justice-centered, citation-organized file.
const legacy = [...new Map(readScdbCsv(await file("data/scdb/legacy_07/SCDB_Legacy_07_justiceCentered_Citation.csv.zip")).rows
  .map((r) => [r.caseId!, r] as const).reverse()).values()].reverse();
const rows = [
  ...modern.map((r) => ({ era: "modern", r })),
  ...legacy.map((r) => ({ era: "legacy", r })),
].map(({ era, r }) => `(${[lit(r.docketId!), lit(r.caseId!), lit(era), lit(scdbInt(r.term)), lit(scdbDate(r.dateDecision)), lit(scdbText(r.usCite)), lit(scdbText(r.docket))].join(",")})`);

const sql = `-- GENERATED by scripts/scotus/build-match-rate-diag.ts from SCDB 2026 Release 01
-- (case-centered, docket-organized) and SCDB Legacy 07 (justice-centered, citation-
-- organized, first row per case). Read-only: matches SCDB dockets to legal_case with the importer's
-- rule and reports the match rate. ${rows.length} SCDB dockets inlined.
\\echo '=== SCDB -> Jurvio match rate (case level: a case matches when any of its dockets does) ==='
WITH raw(scdb_docket_id, scdb_case_id, era, term, decided_on, us_cite, docket) AS (VALUES
${rows.join(",\n")}
),
src AS (SELECT scdb_docket_id, scdb_case_id, era, term::smallint AS term, decided_on::date AS decided_on, us_cite, docket FROM raw),
${scdbMatchCtes("src")},
per_case AS (
  SELECT s.scdb_case_id, min(s.era) AS era, min(s.term) AS term,
         bool_or(m.legal_case_id IS NOT NULL) AS matched,
         (array_agg(m.match_method ORDER BY s.scdb_docket_id) FILTER (WHERE m.legal_case_id IS NOT NULL))[1] AS method,
         bool_or(m.legal_case_id IS NULL AND m.match_candidates > 1) AS ambiguous
  FROM src s JOIN scdb_match m USING (scdb_docket_id)
  GROUP BY s.scdb_case_id
),
dockets AS (
  SELECT s.era, count(*) AS dockets, count(m.legal_case_id) AS dockets_matched, count(DISTINCT m.legal_case_id) AS distinct_jurvio_cases
  FROM src s JOIN scdb_match m USING (scdb_docket_id) GROUP BY ROLLUP (s.era)
)
SELECT 'era' AS dim, coalesce(era, 'all') AS bucket, count(*) AS scdb_cases, count(*) FILTER (WHERE matched) AS matched,
       round(100.0 * count(*) FILTER (WHERE matched) / count(*), 2) AS match_pct,
       count(*) FILTER (WHERE method = 'us_cite') AS by_us_cite,
       count(*) FILTER (WHERE method = 'docket_and_date') AS by_docket_date,
       count(*) FILTER (WHERE method = 'docket_and_term') AS by_docket_term,
       count(*) FILTER (WHERE NOT matched AND ambiguous) AS ambiguous_unmatched
FROM per_case GROUP BY ROLLUP (era)
UNION ALL
SELECT 'decade', (term / 10 * 10)::text, count(*), count(*) FILTER (WHERE matched),
       round(100.0 * count(*) FILTER (WHERE matched) / count(*), 2),
       count(*) FILTER (WHERE method = 'us_cite'), count(*) FILTER (WHERE method = 'docket_and_date'),
       count(*) FILTER (WHERE method = 'docket_and_term'), count(*) FILTER (WHERE NOT matched AND ambiguous)
FROM per_case GROUP BY term / 10 * 10
UNION ALL
SELECT 'recent_term', term::text, count(*), count(*) FILTER (WHERE matched),
       round(100.0 * count(*) FILTER (WHERE matched) / count(*), 2),
       count(*) FILTER (WHERE method = 'us_cite'), count(*) FILTER (WHERE method = 'docket_and_date'),
       count(*) FILTER (WHERE method = 'docket_and_term'), count(*) FILTER (WHERE NOT matched AND ambiguous)
FROM per_case WHERE term >= 2015 GROUP BY term
UNION ALL
SELECT 'dockets', coalesce(era, 'all'), dockets, dockets_matched, round(100.0 * dockets_matched / dockets, 2), distinct_jurvio_cases, NULL, NULL, NULL
FROM dockets
ORDER BY 1, 2;
`;
const out = path.join(root, "scripts/diag/scdb-jurvio-match-rate.sql");
await writeFile(out, sql);
console.log(`wrote ${path.relative(root, out)} (${rows.length} dockets, ${(sql.length / 1e6).toFixed(2)} MB)`);
