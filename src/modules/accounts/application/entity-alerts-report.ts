import { entityMatchCtes } from "./entity-alerts";

/** The test account the live check uses (example.com never receives mail). */
export const ALERTS_TEST_EMAIL = "alerts-qa@example.com";

/**
 * Read-only dry run of judge/topic/party matching for the test account's
 * follows over the last `days` days (as if each follow had been created at
 * the window start), plus what the live job has stored for it. Committed as
 * scripts/diag/entity-alerts-dry-run.sql and run with diagnose-sql-once.
 */
export function entityAlertsDryRunSql(days = 7, email = ALERTS_TEST_EMAIL): string {
  if (!Number.isInteger(days) || days < 1 || days > 30) throw new Error("days must be 1-30");
  if (!/^[a-z0-9.+-]+@[a-z0-9.-]+$/.test(email)) throw new Error("invalid email");
  const from = `now() - interval '${days} days'`;
  const followSource = `(SELECT f.id, f.kind, f.target_key, ${from} AS created_at
        FROM entity_follow f JOIN app_user u ON u.id = f.user_id
        WHERE u.email = '${email}') test_follow`;
  const ctes = entityMatchCtes({ from, to: "now()", follows: followSource });
  return `-- GENERATED by entityAlertsDryRunSql() (src/modules/accounts/application/entity-alerts-report.ts).
-- Do not edit by hand; the unit test fails when this file is stale.
--
-- Read-only dry run: what judge/topic/party alerts would have matched in the
-- last ${days} days for the follows of ${email}, using the same
-- matching query as the alert job. Then what the live job has stored.
\\timing on
\\echo '== follows of the test account'
SELECT f.kind, f.label, f.target_key, f.frequency, f.created_at, f.last_sent_at
FROM entity_follow f JOIN app_user u ON u.id = f.user_id
WHERE u.email = '${email}' ORDER BY f.kind;

\\echo '== dry run: matches in the last ${days} days by follow and event kind'
WITH ${ctes}
SELECT f.kind, f.label, r.event_kind, count(*) AS matches, min(r.occurred_on) AS first_filed, max(r.occurred_on) AS last_filed
FROM ranked r JOIN entity_follow f ON f.id = r.follow_id
GROUP BY 1, 2, 3 ORDER BY 1, 2, 3;

\\echo '== dry run: newest 8 matches per follow (public-safe summaries as they would be emailed)'
WITH ${ctes}
SELECT f.kind, f.label, r.event_kind, r.occurred_on, c.public_id, left(c.caption, 80) AS caption, court.name AS court, r.summary
FROM ranked r JOIN entity_follow f ON f.id = r.follow_id
JOIN legal_case c ON c.id = r.case_id JOIN court ON court.id = c.court_id
WHERE r.rn <= 8
ORDER BY f.kind, f.label, r.rn;

\\echo '== live job: stored matches for the test account'
SELECT f.kind, f.label, i.event_kind, count(*) AS stored, count(i.sent_at) AS sent, min(i.found_at) AS first_found, max(i.found_at) AS last_found
FROM entity_alert_item i JOIN entity_follow f ON f.id = i.follow_id JOIN app_user u ON u.id = f.user_id
WHERE u.email = '${email}'
GROUP BY 1, 2, 3 ORDER BY 1, 2, 3;

\\echo '== live job: cursors and all follows'
SELECT source, scanned_to, now() - scanned_to AS lag FROM entity_alert_cursor ORDER BY source;
SELECT kind, frequency, count(*) AS follows FROM entity_follow GROUP BY 1, 2 ORDER BY 1, 2;
SELECT count(*) AS items, count(*) FILTER (WHERE sent_at IS NULL) AS queued FROM entity_alert_item;
`;
}
