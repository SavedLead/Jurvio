import { NATURE_OF_SUIT } from "./nature-of-suit";
import { formatPublicCaseDate } from "./scotus-display";

/**
 * Deterministic, template-based answers for the four case-page questions when no
 * verified editorial summary exists (every non-SCOTUS case today).
 *
 * Every sentence is assembled only from structured fields Jurvio already holds
 * for a displayable case: caption, docket number, court, filed / terminated /
 * decided dates, the civil cover sheet's nature-of-suit code, the cause of
 * action, the count of displayable docket entries and the count of Jurvio
 * opinions that cite the case. Nothing is inferred beyond those fields, nothing
 * is generated by a model, and no outcome is claimed that the record does not
 * state. A field that is missing simply drops its sentence.
 */
export type CourtKind = "district" | "appellate" | "supreme" | "bankruptcy" | "other";

export interface RecordAnswerInput {
  caption: string;
  docketNumber: string;
  courtName: string;
  courtKind: CourtKind;
  filedOn: string | null;
  terminatedOn: string | null;
  decidedOn: string | null;
  natureOfSuit: string | null;
  causeOfAction: string | null;
  docketEntryCount: number;
  citedByCount: number;
  hasReadableOpinion: boolean;
  /** Filing date of the case's published opinion document, when known. */
  opinionFiledOn?: string | null;
  /** Category from a PACER caption tag such as "(HC)"; see captionTag(). */
  captionCategory?: string | null;
}

export interface RecordAnswers {
  happened: string | null;
  about: string | null;
  matters: string | null;
  outcome: string | null;
}

const COURT_SYSTEM_SUFFIX = /\s*[-–—]\s*(live system|live database|live|cm\/?ecf.*|nextgen.*|test system)\s*$/i;

/** Court names imported from PACER sometimes carry the CM/ECF system label ("- Live System"). */
export function cleanCourtName(name: string): string {
  const cleaned = name.replace(COURT_SYSTEM_SUFFIX, "").trim();
  return cleaned || name.trim();
}

export function courtKindFromJurisdiction(jurisdiction: string | null | undefined, courtName = "", courtCode?: string | null): CourtKind {
  const value = (jurisdiction ?? "").trim().toUpperCase();
  if ((courtCode ?? "").toLowerCase() === "scotus" || /supreme court of the united states/i.test(courtName) || /^supreme court$/i.test(courtName.trim())) return "supreme";
  if (value === "FS") return "other"; // CourtListener "Federal Special": Claims, Tax, Customs, CIT ...
  if (value === "F" || value === "FEDERAL APPELLATE" || /court of appeals|circuit/i.test(courtName)) return "appellate";
  if (value === "FB" || value === "FBP" || /bankruptcy/i.test(courtName)) return "bankruptcy";
  if (value === "FD" || value === "FEDERAL DISTRICT" || /district/i.test(courtName)) return "district";
  return "other";
}

/** PACER caption tags some districts prepend (E.D. Cal.: "(HC) Kumar v. Moss"). */
const CAPTION_TAGS: Record<string, string> = {
  HC: "habeas corpus",
  PC: "prisoner civil rights",
  SS: "social security",
};

const CATEGORY_MEANINGS: Record<string, string> = {
  "habeas corpus": "a petition asking the court to decide whether a person's detention is lawful",
  "prisoner civil rights": "a civil rights claim brought by a person in custody",
  "social security": "a request for court review of a Social Security benefits decision",
};

export function captionTag(caption: string): string | null {
  const match = /^\s*\(([A-Z]{2})\)\s+/.exec(caption);
  return match?.[1] ? CAPTION_TAGS[match[1]] ?? null : null;
}

/** The case-type segment of a federal docket number, e.g. "1:26-cv-08930" -> "cv". */
export function docketCaseType(docketNumber: string): string | null {
  const match = /^\s*(?:\d+:)?\d{2,4}-([a-z]{1,4})-\d+/i.exec(docketNumber);
  return match?.[1] ? match[1].toLowerCase() : null;
}

export interface ParsedNatureOfSuit {
  code: string | null;
  label: string;
  category: string | null;
}

/** Accepts "440", "440 Civil Rights: Other", or a bare label such as "Civil Rights: Other". */
export function parseNatureOfSuit(raw: string | null | undefined): ParsedNatureOfSuit | null {
  const value = (raw ?? "").trim();
  if (!value || /^(0+|unknown|n\/?a|none|-)$/i.test(value)) return null;
  // PACER RSS sometimes prefixes the code with a category digit ("2463", "3440").
  const match = /^\d?(\d{3})(?:\s+[-:.]?\s*(.*)|[-:.]\s*(.*))?$/.exec(value);
  if (match?.[1]) {
    const known = NATURE_OF_SUIT.get(match[1]);
    if (known) return { code: known.code, label: known.label, category: known.category };
    const label = (match[2] ?? match[3] ?? "").trim();
    return label ? { code: match[1], label, category: null } : null;
  }
  return { code: null, label: value, category: null };
}

/** "42:1983 Civil Rights Act" -> "42 U.S.C. § 1983 (Civil Rights Act)". */
export function formatCauseOfAction(raw: string | null | undefined): string | null {
  const value = (raw ?? "").replace(/\s+/g, " ").trim();
  if (!value || /^(0+|unknown|n\/?a|none|no cause code entered|-)$/i.test(value)) return null;
  const match = /^(\d{1,2})\s*:\s*(\d+[a-z0-9]*)((?:\([a-z0-9]+\))*)\s*[-:]?\s*(.*)$/i.exec(value);
  if (!match) return value;
  const [, title = "", rawSection = "", subsections = "", rest = ""] = match;
  // PACER appends office suffixes to some sections ("2241fd", "2241in"); a single letter ("2000e") is a real section.
  const section = rawSection.replace(/^(\d+[a-z]?)[a-z]{2,}$/i, "$1");
  const citation = `${title} U.S.C. § ${section}${subsections}`;
  let description = rest.trim().replace(/^[-:]\s*/, "");
  // PACER truncates long descriptions mid-parenthesis ("Habeas Corpus (federa").
  if ((description.match(/\(/g) ?? []).length > (description.match(/\)/g) ?? []).length) {
    description = description.slice(0, description.lastIndexOf("(")).trim();
  }
  return description ? `${citation} (${description})` : citation;
}

function splitCaption(caption: string): { first: string; second: string } | null {
  const match = /^(.+?)\s+(?:v|vs)\.?\s+(.+)$/i.exec(caption.trim());
  if (!match) return null;
  const first = (match[1] ?? "").trim();
  const second = (match[2] ?? "").trim();
  return first && second ? { first, second } : null;
}

const DIRECTION_WORDS: Record<string, string> = { N: "Northern", S: "Southern", E: "Eastern", W: "Western", M: "Middle", C: "Central" };

/**
 * Court name as it reads in a sentence: "District Court, W.D. Texas" becomes
 * "the U.S. District Court for the Western District of Texas"; other names get a leading "the".
 */
export function courtPhrase(courtName: string) {
  const name = courtName.replace(/\s+/g, " ").trim().replace(/\.$/, "");
  const cl = /^(District|Bankruptcy) Court, (?:([NSEWMC])\.\s?)?D\.\s?(.+)$/.exec(name);
  if (cl?.[1] && cl[3]) {
    const district = cl[2] ? `${DIRECTION_WORDS[cl[2]]} District` : "District";
    const court = cl[1] === "District" ? "U.S. District Court" : "U.S. Bankruptcy Court";
    return `the ${court} for the ${district} of ${cl[3].trim()}`;
  }
  const comma = /^(United States (?:District|Bankruptcy) Court), (?:([NSEWMC])\.\s?)?D\.\s?(.+)$/.exec(name);
  if (comma?.[1] && comma[3]) {
    const district = comma[2] ? `${DIRECTION_WORDS[comma[2]]} District` : "District";
    return `the ${comma[1]} for the ${district} of ${comma[3].trim()}`;
  }
  return /^the\b/i.test(name) ? name : `the ${name}`;
}

/** Decodes HTML character references, including double-encoded ones ("&#x26;#167;" -> "§"). */
export function decodeHtmlEntities(value: string): string {
  const named: Record<string, string> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", sect: "§" };
  let current = value;
  for (let pass = 0; pass < 3; pass++) {
    const next = current.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (match, code: string) => {
      if (code[0] === "#") {
        const point = code[1]?.toLowerCase() === "x" ? parseInt(code.slice(2), 16) : parseInt(code.slice(1), 10);
        return Number.isFinite(point) && point > 0 && point <= 0x10ffff ? String.fromCodePoint(point) : match;
      }
      return named[code.toLowerCase()] ?? match;
    });
    if (next === current) break;
    current = next;
  }
  return current;
}

/**
 * Magistrate / criminal-docket captions that name a thing rather than a person
 * (search warrants, seized devices, premises, accounts, in rem property). These
 * are never "United States v. <defendant>" prosecutions.
 */
export function isInRemCaption(caption: string): boolean {
  const value = caption.trim();
  return /^\d/.test(value)
    || /\b(devices?|property|properties|premises|accounts?|warrants?|search|seized|seizure|residence|vehicles?|cellular|phones?|iphones?|e-?mail|tracking|currency|funds|parcels?|packages?|storage|information associated)\b/i.test(value);
}

function article(word: string) {
  return /^[aeiou]/i.test(word) ? "An" : "A";
}

function sentence(text: string) {
  const trimmed = text.trim();
  return /[.!?]$/.test(trimmed) ? trimmed : `${trimmed}.`;
}

function plural(count: number, one: string, many: string) {
  return `${count.toLocaleString("en-US")} ${count === 1 ? one : many}`;
}

function caseKindPhrase(input: RecordAnswerInput, nos: ParsedNatureOfSuit | null) {
  const type = input.courtKind === "district" ? docketCaseType(input.docketNumber) : null;
  if (input.courtKind === "appellate") return "An appeal";
  if (input.courtKind === "supreme") return "A Supreme Court case";
  if (input.courtKind === "bankruptcy") return "A bankruptcy case";
  if (type === "cr") return "A federal criminal case";
  if (type === "cv" || nos) {
    const category = nos?.category ?? input.captionCategory ?? null;
    return category ? `${article(category)} ${category} case` : "A civil case";
  }
  if (type === "mj") return "A federal magistrate judge matter";
  if (type === "po") return "A federal petty offense case";
  if (type === "mc") return "A miscellaneous case";
  return "A case";
}

/** Short case-type label for meta descriptions, e.g. "Civil rights case" or "Federal criminal case". */
export function caseTypeLabel(input: Pick<RecordAnswerInput, "courtKind" | "docketNumber" | "natureOfSuit" | "captionCategory">): string {
  const nos = input.courtKind === "district" || input.courtKind === "other" ? parseNatureOfSuit(input.natureOfSuit) : null;
  const phrase = caseKindPhrase({ ...input } as RecordAnswerInput, nos).replace(/^(A|An)\s+/, "");
  return phrase.charAt(0).toUpperCase() + phrase.slice(1);
}

export function buildRecordAnswers(input: RecordAnswerInput): RecordAnswers {
  const court = cleanCourtName(input.courtName);
  const nos = input.courtKind === "district" || input.courtKind === "other" ? parseNatureOfSuit(input.natureOfSuit) : null;
  const cause = input.courtKind === "district" || input.courtKind === "other" ? formatCauseOfAction(input.causeOfAction) : null;
  const filed = formatPublicCaseDate(input.filedOn);
  const terminated = formatPublicCaseDate(input.terminatedOn);
  const decided = formatPublicCaseDate(input.decidedOn) ?? (input.hasReadableOpinion ? formatPublicCaseDate(input.opinionFiledOn) : null);
  const type = docketCaseType(input.docketNumber);
  const parties = splitCaption(input.caption);
  const district = input.courtKind === "district";

  // What happened: kind, filing, court, parties, and the latest dated milestone.
  const opening: string[] = [caseKindPhrase(input, nos)];
  if (nos?.code) opening.push(`(nature of suit ${nos.code}, ${nos.label.toLowerCase()})`);
  if (filed) opening.push(`filed on ${filed}`);
  opening.push(`in ${courtPhrase(court)}`);
  if (parties && input.courtKind === "district" && type === "cv") {
    opening.push(`by ${parties.first} against ${parties.second}`);
  } else if (parties && district && (type === "cr" || type === "mj" || type === "po") && /^(united states|usa|u\.s\.a?\.?)( of america)?$/i.test(parties.first) && !isInRemCaption(parties.second)) {
    opening.push(`in which the United States is prosecuting ${parties.second}`);
  } else if (parties && !district) {
    opening.push(`between ${parties.first} and ${parties.second}`);
  }
  const happenedParts = [sentence(opening.join(" "))];
  if (terminated) happenedParts.push(`The court record shows the case was closed on ${terminated}.`);
  else if (decided) happenedParts.push(`The court issued a decision on ${decided}.`);
  else if (input.hasReadableOpinion) happenedParts.push("The court's written opinion is available on this page.");
  else if (district) happenedParts.push("No closing date appears in the court record Jurvio holds.");
  if (input.docketEntryCount > 0) happenedParts.push("The docket entries Jurvio holds are listed in the timeline on this page.");
  const hasCoreFact = Boolean(filed || terminated || decided || nos || parties || input.hasReadableOpinion);
  const happened = hasCoreFact ? happenedParts.join(" ") : null;

  // What is this about: only what the filing itself declares.
  const aboutParts: string[] = [];
  if (nos) {
    aboutParts.push(
      nos.code
        ? `The court record classifies this case under nature of suit ${nos.code}: ${nos.label}${nos.category ? ` (${nos.category})` : ""}.`
        : `The court record classifies this case as: ${sentence(nos.label)}`,
    );
  }
  if (cause) aboutParts.push(`The cause of action listed is ${sentence(cause)}`);
  if (!nos && input.captionCategory) {
    const meaning = CATEGORY_MEANINGS[input.captionCategory];
    aboutParts.push(`The court's docket caption marks this as a ${input.captionCategory} case${meaning ? `: ${meaning}` : ""}.`);
  }
  if (!aboutParts.length && type === "cr" && input.courtKind === "district") {
    aboutParts.push("This is a federal criminal prosecution. The specific charges are listed in the court's charging documents and docket.");
  }
  const about = aboutParts.length ? aboutParts.join(" ") : null;

  // Why it matters: only measurable reliance by later opinions.
  const matters = input.citedByCount > 0
    ? `${plural(input.citedByCount, "court opinion", "court opinions")} on Jurvio ${input.citedByCount === 1 ? "cites" : "cite"} this case, which shows other courts have relied on or discussed it.`
    : null;

  // Outcome: dates the record states; never a characterization it does not.
  let outcome: string | null = null;
  if (decided && input.hasReadableOpinion) {
    outcome = `The court issued its decision on ${decided}. The full text of the opinion is available on this page.`;
  } else if (terminated) {
    outcome = `The court record shows the case was closed on ${terminated}. Jurvio has not yet verified how it was resolved; the docket entries are the source for the final orders.`;
  } else if (decided) {
    outcome = `The court issued a decision on ${decided}. Jurvio has not yet verified a plain-English holding.`;
  }

  return { happened, about, matters, outcome };
}

export interface CaseMetaInput {
  caption: string;
  docketNumber: string;
  courtName: string;
  courtKind: CourtKind;
  natureOfSuit: string | null;
  judgeName: string | null;
  filedOn: string | null;
  terminatedOn: string | null;
  decidedOn: string | null;
  officialCitation?: string | null;
  captionCategory?: string | null;
}

/** Meta description: case type, court, judge and status, all from record fields. */
export function buildCaseMetaDescription(input: CaseMetaInput): string {
  const court = cleanCourtName(input.courtName);
  const filed = formatPublicCaseDate(input.filedOn);
  const terminated = formatPublicCaseDate(input.terminatedOn);
  const decided = formatPublicCaseDate(input.decidedOn);
  const status = terminated
    ? `Closed ${terminated}`
    : decided
      ? `Decided ${decided}`
      : "No closing date on record";
  return [
    `${input.caption}: ${caseTypeLabel(input).toLowerCase()} in ${courtPhrase(court)}, docket ${input.docketNumber}`,
    input.judgeName ? `Judge: ${input.judgeName}` : null,
    filed ? `Filed ${filed}` : null,
    `Status: ${status}`,
    input.officialCitation ?? null,
  ].filter(Boolean).map((part) => sentence(part as string)).join(" ");
}
